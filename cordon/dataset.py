"""Typed loading of the evaluation dataset.

The dataset is generated by ``dataset/generate_dataset.py`` and validated by
``dataset/validate_dataset.py``; this module only parses the artifact into
the domain models and fingerprints it for run manifests.
"""

import hashlib
import json
from pathlib import Path

from cordon.schema import Dataset

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET_PATH = REPO_ROOT / "dataset" / "scenarios.json"


def load_dataset(path: Path | str = DEFAULT_DATASET_PATH) -> Dataset:
    raw = json.loads(Path(path).read_text())
    return Dataset.model_validate(raw)


def dataset_hash(path: Path | str = DEFAULT_DATASET_PATH) -> str:
    """SHA-256 of the dataset artifact, recorded in every run manifest."""
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()
